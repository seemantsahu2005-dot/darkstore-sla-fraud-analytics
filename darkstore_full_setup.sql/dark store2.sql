CREATE DATABASE IF NOT EXISTS darkstore_analytics;
USE darkstore_analytics;

DROP TABLE IF EXISTS refund_claims;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS inventory;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS delivery_partners;
DROP TABLE IF EXISTS dark_stores;

CREATE TABLE dark_stores (
  store_id INT PRIMARY KEY, store_name VARCHAR(50), city VARCHAR(30),
  zone VARCHAR(20), capacity_sqft INT, launch_date DATE
);
CREATE TABLE delivery_partners (
  partner_id INT PRIMARY KEY, partner_name VARCHAR(50), store_id INT,
  vehicle_type VARCHAR(20), join_date DATE,
  FOREIGN KEY (store_id) REFERENCES dark_stores(store_id)
);
CREATE TABLE products (
  product_id INT PRIMARY KEY, product_name VARCHAR(100), category VARCHAR(50),
  unit_price DECIMAL(8,2), shelf_life_days INT
);
CREATE TABLE customers (
  customer_id INT PRIMARY KEY, customer_name VARCHAR(100), city VARCHAR(30)
);
CREATE TABLE inventory (
  inventory_id INT PRIMARY KEY, store_id INT, product_id INT, stock_qty INT,
  reorder_level INT, last_restocked DATE,
  FOREIGN KEY (store_id) REFERENCES dark_stores(store_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);
CREATE TABLE orders (
  order_id INT PRIMARY KEY, customer_id INT, store_id INT, partner_id INT,
  order_time DATETIME, promised_delivery_time DATETIME,
  actual_delivery_time DATETIME NULL, order_value DECIMAL(10,2), order_status VARCHAR(20),
  FOREIGN KEY (store_id) REFERENCES dark_stores(store_id),
  FOREIGN KEY (partner_id) REFERENCES delivery_partners(partner_id),
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);
CREATE TABLE order_items (
  order_item_id INT PRIMARY KEY, order_id INT, product_id INT, qty INT,
  FOREIGN KEY (order_id) REFERENCES orders(order_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);
CREATE TABLE refund_claims (
  claim_id INT PRIMARY KEY, order_id INT, customer_id INT, claim_reason VARCHAR(50),
  claim_amount DECIMAL(10,2), claim_date DATETIME, resolution_status VARCHAR(20),
  FOREIGN KEY (order_id) REFERENCES orders(order_id)
);

SET FOREIGN_KEY_CHECKS=0;

