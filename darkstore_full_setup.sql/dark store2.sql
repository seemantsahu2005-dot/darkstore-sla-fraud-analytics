-- Q1: SLA breach rate by store + hour
select store_id, hour(order_time) as order_hour ,
count(*) as total_orders,
sum(case when actual_delivery_time>promised_delivery_time then 1 else 0 end) as breaches,
round(sum(case when actual_delivery_time > promised_delivery_time then 1 else 0 end)*100.0/count(*),2)as breach_pct
from orders
where order_status = 'delivered'
group by store_id , hour(order_time)
HAVING COUNT(*) >= 5
order by breach_pct desc;

SELECT
  ROUND(SUM(CASE WHEN actual_delivery_time > promised_delivery_time THEN 1 ELSE 0 END)*100.0/COUNT(*),2) AS overall_breach_pct,
  COUNT(*) AS total_delivered_orders
FROM orders
WHERE order_status = 'delivered';

-- Q2: Delivery partner scorecard

select p.partner_id , p.partner_name , p.store_id,
count(o.order_id)as total_deliveries,
avg(timestampdiff(minute,o.order_time, o.actual_delivery_time))as avg_delivery_min,
sum(case when o.actual_delivery_time > o.promised_delivery_time then 1 else 0 end )*100.0/count(o.order_id) as breach_pct
from delivery_partners p 
join orders o on p.partner_id = o.partner_id
where o.order_status = "delivered"
group by p.partner_id, p.partner_name , p.store_id
order by breach_pct desc;

