-- Q3: Fraud / refund-abuse detection

select o.customer_id,
count(distinct o.order_id)as total_orders,
count(distinct r.claim_id)as total_claim,
round(count(distinct r.claim_id)*100.0/count(distinct o.order_id),2)as claim_rate_pct,
sum(r.claim_amount)as total_refund_value
from orders o 
join refund_claims r on o.order_id = r.order_id 
group by o.customer_id 
having count(distinct o.order_id)>=3
and count(distinct r.claim_id)*100.0/count(distinct o.order_id)>30
order by claim_rate_pct desc;

-- Q4: Dead stock / reorder alert
select s.store_name , pr.product_name , i.stock_qty , i.reorder_level,
datediff(curdate(),i.last_restocked)as days_since_restock
from inventory i 
join dark_stores s on i.store_id = s.store_id
join products pr on i.product_id = pr.product_id
where i.stock_qty <= i.reorder_level
order by days_since_restock desc ;

